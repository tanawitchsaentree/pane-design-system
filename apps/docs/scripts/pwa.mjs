// Makes the built book an installable app (PWA): a manifest whose colours come from the tokens, and a
// service worker that keeps the shell and every page's code for offline reading. Runs after vite build,
// because the worker lists the files the build produced. G-PWA1 checks the result in a browser.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;
const tokens = JSON.parse(readFileSync(new URL('../../../packages/tokens/build/json/tokens.json', import.meta.url), 'utf8'));
const val = (name) => { const t = tokens[name] ?? Object.values(tokens).find((x) => x.name === name); return t?.value ?? t?.$value; };
const page = String(val('surface.page') ?? val('color.graphite.950') ?? '#141418');
const { version } = JSON.parse(readFileSync(new URL('../../../packages/react/package.json', import.meta.url), 'utf8'));

writeFileSync(path.join(dist, 'manifest.webmanifest'), JSON.stringify({
  name: 'Pane design system', short_name: 'Pane', description: 'The Pane book: components, tokens and patterns, readable offline.',
  id: '/', start_url: '/', scope: '/', display: 'standalone', orientation: 'any', background_color: page, theme_color: page, lang: 'en',
  icons: [
    { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: '/icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}, null, 2));

// the shell and every hashed asset; large evidence files and scene photos are cached the first time they load
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = path.join(d, f); if (statSync(p).isDirectory()) walk(p); else files.push('/' + path.relative(dist, p)); } };
walk(dist);
const pre = files.filter((f) => /^\/(index\.html|assets\/.+\.(js|css|woff2?)|icons\/.+|favicon.*|apple-touch-icon\.png|manifest\.webmanifest|pane-.+\.css)$/.test(f));
const hash = createHash('sha256').update(pre.join('|') + version).digest('hex').slice(0, 12);
writeFileSync(path.join(dist, 'sw.js'), `// generated by apps/docs/scripts/pwa.mjs
const CACHE = 'pane-${hash}';
const PRE = ${JSON.stringify(pre)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('pane-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const r = e.request; if (r.method !== 'GET' || new URL(r.url).origin !== location.origin) return;
  // pages: the network first so the book is current, the cached shell when offline (it is one app)
  if (r.mode === 'navigate') { e.respondWith(fetch(r).catch(() => caches.match('/index.html'))); return; }
  // everything else: the cache first, then the network, keeping what was fetched for next time
  e.respondWith(caches.match(r).then((hit) => hit || fetch(r).then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(r, copy)); } return res; })));
});
`);
console.log(`✓ pwa: manifest + sw.js (${pre.length} files precached, cache ${hash})`);
