import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

/**
 * Postbuild step for dial-tokens — QA W2 Wave 2 finding #5 (D-014).
 *
 * Style Dictionary only emits the MANUAL toggle path for contrast-more:
 * `[data-theme="light"][data-contrast="more"]` in build/css/light-contrast-more.css (dev/demo
 * opt-in, per braun-flat.md rule 5 + docs/BLUEPRINT.md §4.4). There was no `@media
 * (prefers-contrast: more)` block anywhere in the build output, so a real user's OS/browser
 * "increase contrast" setting was never auto-detected — only a data-attribute a developer sets
 * manually. Both paths must work per §4.4 (auto-adapt AND dev toggle/demo).
 *
 * Style Dictionary's format API doesn't have a first-class "wrap this whole theme in a media
 * query" option, so instead of fighting the formatter this is a small, self-contained postbuild
 * script: diff the resolved custom-property values between light.css (:root) and
 * light-contrast-more.css ([data-theme="light"][data-contrast="more"]) — both already built by
 * style-dictionary.config.mjs — and re-emit ONLY the properties that actually changed (currently
 * just color.border.*, per contrast-more.json's own scope note) inside a `:root` selector nested
 * in `@media (prefers-contrast: more)`, appended to the end of light.css.
 *
 * Cascade note: `:root` has the same specificity as the `[data-theme="light"][data-contrast="more"]`
 * attribute selector's *lower* bound... actually the attribute selector (two attributes) has
 * HIGHER specificity than a lone `:root` pseudo-class, so when a developer manually sets
 * data-contrast="more" that explicit choice still wins over the OS-level media query — which is
 * the right precedence (explicit dev/demo override > implicit OS preference). When neither is
 * set but the OS reports prefers-contrast:more, this new block is the only thing that fires,
 * closing the auto-adapt gap. Scope matches contrast-more.json today: light theme only (dark+
 * contrast-more is intentionally not generated yet, see contrast-more.json's own note) — if the
 * OS prefers more contrast while the app is in dark mode, dark.css's unconditional
 * `[data-theme="dark"]` block is loaded after light.css in every consumer (Storybook preview.ts,
 * component build) and wins the cascade tie, so this never leaks incorrect light-theme borders
 * into dark mode.
 */

const __dirname = dirname(fileURLToPath(import.meta.url));
const CSS_DIR = join(__dirname, "../build/css");

const LIGHT = join(CSS_DIR, "light.css");
const LIGHT_CONTRAST_MORE = join(CSS_DIR, "light-contrast-more.css");

const VAR_RE = /^\s*(--ds-[a-z0-9-]+):\s*(.+?);\s*$/;

function parseVars(css) {
  const vars = new Map();
  for (const line of css.split("\n")) {
    const m = line.match(VAR_RE);
    if (m) vars.set(m[1], m[2]);
  }
  return vars;
}

const lightCss = readFileSync(LIGHT, "utf8");
const contrastMoreCss = readFileSync(LIGHT_CONTRAST_MORE, "utf8");

const lightVars = parseVars(lightCss);
const contrastMoreVars = parseVars(contrastMoreCss);

const changed = [];
for (const [name, value] of contrastMoreVars) {
  if (lightVars.get(name) !== value) changed.push([name, value]);
}

if (changed.length === 0) {
  throw new Error(
    "postbuild-contrast-media: light-contrast-more.css has 0 properties different from light.css — nothing to " +
      "put in the @media (prefers-contrast: more) block. contrast-more.json probably stopped overriding anything; check src/semantic/contrast-more.json.",
  );
}

const alreadyInjected = lightCss.includes("@media (prefers-contrast: more)");
if (alreadyInjected) {
  console.log("postbuild-contrast-media: light.css already has a @media (prefers-contrast: more) block — skipping (build.mjs should not run this twice without a clean build).");
  process.exit(0);
}

const block = `
/**
 * Auto-generated by postbuild-contrast-media.mjs (D-014, QA W2 Wave 2 finding #5) — real
 * OS/browser "increase contrast" auto-detection, mirroring the manual
 * [data-theme="light"][data-contrast="more"] override above with the same resolved values.
 * Scope: light theme only, matching contrast-more.json (dark+contrast-more not generated yet).
 */
@media (prefers-contrast: more) {
  :root {
${changed.map(([name, value]) => `    ${name}: ${value};`).join("\n")}
  }
}
`;

writeFileSync(LIGHT, lightCss + block);
console.log(`postbuild-contrast-media: appended @media (prefers-contrast: more) block to light.css (${changed.length} properties: ${changed.map(([n]) => n).join(", ")})`);
