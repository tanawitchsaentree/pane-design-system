import StyleDictionary from "style-dictionary";

/**
 * Build entrypoint for @dial/tokens.
 * Runs: `node ./scripts/build.mjs` (invoked by `pnpm --filter @dial/tokens build`)
 *
 * Registers one custom format (javascript/tailwind-preset) then delegates to
 * style-dictionary.config.mjs, which defines one Style Dictionary instance per theme
 * (light / dark / light-contrast-more) so each theme's CSS/SCSS/JSON/TS output builds
 * from primitive -> semantic composition per docs/BLUEPRINT.md §3.1.
 */

StyleDictionary.registerFormat({
  name: "javascript/tailwind-preset",
  format: ({ dictionary }) => {
    // Build a nested JS object keyed by dot-path (minus the leading category) so it can be
    // spread into tailwind.config.js `theme.extend`. Kept intentionally simple: consumers that
    // want deeper Tailwind color-scale integration can post-process build/json/light.json instead.
    const theme = { colors: {}, spacing: {}, fontSize: {}, borderRadius: {}, boxShadow: {} };

    for (const token of dictionary.allTokens) {
      const path = token.path.join("-");
      const value = token.$value ?? token.value;
      if (token.path[0] === "color") theme.colors[path] = value;
      if (token.path[0] === "space" || token.path[0] === "size") theme.spacing[path] = value;
      if (token.path[0] === "fontSize") theme.fontSize[path] = value;
      if (token.path[0] === "radius") theme.borderRadius[path] = value;
    }

    return `// Auto-generated by @dial/tokens — do not edit by hand. Source: packages/tokens/src/ (all *.json under primitive/semantic).
module.exports = {
  theme: {
    extend: ${JSON.stringify(theme, null, 2)}
  }
};
`;
  },
});

const configs = (await import("../style-dictionary.config.mjs")).default;

for (const cfg of configs) {
  const sd = new StyleDictionary({ ...cfg, log: { verbosity: "verbose" } });
  await sd.buildAllPlatforms();
}

console.log("\n@dial/tokens build complete -> packages/tokens/build/{css,scss,json,ts,tailwind}");
