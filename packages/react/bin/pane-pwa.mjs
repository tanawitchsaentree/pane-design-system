#!/usr/bin/env node
// pane-pwa: makes a built site installable on any phone (Android "Install app", iPhone "Add to Home
// Screen") and readable offline. Run it after your build, on the folder you deploy:
//   npx pane-pwa --dist dist --name "Brick Forge" --short "Forge" --icon192 public/icon-192.png --icon512 public/icon-512.png [--maskable public/maskable-512.png] [--theme "#141418"] [--start /]
// It writes manifest.webmanifest and sw.js into the folder, copies the icons to icons/, and prints the
// two lines to put in your HTML <head> and the one line to put in your app's entry.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

const arg = (k, d) => { const i = process.argv.indexOf(`--${k}`); return i > 0 ? process.argv[i + 1] : d; };
const dist = path.resolve(arg('dist', 'dist'));
const name = arg('name'); const short = arg('short', name);
const theme = arg('theme', '#141418'); const start = arg('start', '/');
const icons = { '192x192': arg('icon192'), '512x512': arg('icon512') }; const maskable = arg('maskable');
const fail = (m) => { console.error(`✗ pane-pwa: ${m}`); process.exit(1); };
if (!existsSync(dist)) fail(`no build folder at ${dist}; run your build first`);
if (!name) fail('--name is required (the app name under the icon)');
for (const [s, f] of Object.entries(icons)) if (!f || !existsSync(f)) fail(`--icon${s.split('x')[0]} must point to a ${s} PNG`);
if (!/^#[0-9a-f]{6}$/i.test(theme)) fail('--theme must be a #rrggbb colour, the bar colour on Android');

mkdirSync(path.join(dist, 'icons'), { recursive: true });
const list = [];
for (const [s, f] of Object.entries(icons)) { const to = `icons/icon-${s.split('x')[0]}.png`; copyFileSync(f, path.join(dist, to)); list.push({ src: `/${to}`, sizes: s, type: 'image/png', purpose: 'any' }); }
if (maskable && existsSync(maskable)) { copyFileSync(maskable, path.join(dist, 'icons/maskable-512.png')); list.push({ src: '/icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }); }
else console.warn('  note: no --maskable icon; Android will crop the plain one into a circle');
writeFileSync(path.join(dist, 'manifest.webmanifest'), JSON.stringify({ name, short_name: short, id: start, start_url: start, scope: '/', display: 'standalone', background_color: theme, theme_color: theme, icons: list }, null, 2));

const files = []; const walk = (d) => { for (const f of readdirSync(d)) { const p = path.join(d, f); if (statSync(p).isDirectory()) walk(p); else files.push('/' + path.relative(dist, p).split(path.sep).join('/')); } }; walk(dist);
const pre = files.filter((f) => /\.(html|js|css|woff2?|webmanifest)$/.test(f) || f.startsWith('/icons/')).filter((f) => f !== '/sw.js' && statSync(path.join(dist, f)).size < 2_000_000);
const hash = createHash('sha256').update(pre.map((f) => f + statSync(path.join(dist, f)).size).join('|')).digest('hex').slice(0, 12);
writeFileSync(path.join(dist, 'sw.js'), `// generated by pane-pwa
const CACHE = 'pane-pwa-${hash}';
const PRE = ${JSON.stringify(pre)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('pane-pwa-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const r = e.request; if (r.method !== 'GET' || new URL(r.url).origin !== location.origin) return;
  if (r.mode === 'navigate') { e.respondWith(fetch(r).catch(() => caches.match(new URL(r.url).pathname).then((hit) => hit || caches.match('/index.html')))); return; }
  e.respondWith(caches.match(r).then((hit) => hit || fetch(r).then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(r, copy)); } return res; })));
});
`);
console.log(`✓ pane-pwa: manifest.webmanifest and sw.js in ${path.relative(process.cwd(), dist) || '.'} (${pre.length} files kept for offline)
  In <head>:
    <link rel="manifest" href="/manifest.webmanifest">
    <link rel="apple-touch-icon" href="/icons/icon-192.png">
    <meta name="theme-color" content="${theme}">
  In your app's entry (or a <script> at the end of <body>):
    if ('serviceWorker' in navigator) addEventListener('load', () => navigator.serviceWorker.register('/sw.js'));
  The site must be served over HTTPS (Cloudflare Pages, Netlify and Vercel are); localhost works for testing.`);
